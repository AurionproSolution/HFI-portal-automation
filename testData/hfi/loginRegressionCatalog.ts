/**
 * Official Login module regression catalog (approved functional baseline).
 * TC-001..TC-042 → HFS-T0001..HFS-T0042
 */

export type LoginCaseType =
  | "UI"
  | "Security"
  | "Positive"
  | "Negative"
  | "NFR"
  | "Edge"
  | "Alternate";

export type LoginCasePriority = "High" | "Medium" | "Low";

export interface LoginRegressionCase {
  id: string;
  legacyId: string;
  title: string;
  type: LoginCaseType;
  priority: LoginCasePriority;
  acFlowRef: string;
  preconditions: string;
  steps: string[];
  testData: string;
  expectedResult: string;
}

function tc(
  index: number,
  title: string,
  type: LoginCaseType,
  priority: LoginCasePriority,
  acFlowRef: string,
  preconditions: string,
  steps: string[],
  testData: string,
  expectedResult: string,
): LoginRegressionCase {
  const n = String(index).padStart(4, "0");
  return {
    id: `HFS-T${n}`,
    legacyId: `TC-${String(index).padStart(3, "0")}`,
    title,
    type,
    priority,
    acFlowRef,
    preconditions,
    steps,
    testData,
    expectedResult,
  };
}

