/** Official Reset Password catalog TC-001..TC-048 → HFS-T0043..HFS-T0090 */

export type ResetPasswordCaseType =
  | "UI"
  | "Security"
  | "Positive"
  | "Negative"
  | "NFR"
  | "Edge"
  | "Alternate";

export type ResetPasswordCasePriority = "High" | "Medium" | "Low";

export interface ResetPasswordCase {
  id: string;
  legacyId: string;
  title: string;
  type: ResetPasswordCaseType;
  priority: ResetPasswordCasePriority;
  acFlowRef: string;
  preconditions: string;
  steps: string[];
  testData: string;
  expectedResult: string;
}

function tc(
  index: number,
  title: string,
  type: ResetPasswordCaseType,
  priority: ResetPasswordCasePriority,
  acFlowRef: string,
  preconditions: string,
  steps: string[],
  testData: string,
  expectedResult: string,
): ResetPasswordCase {
  const hfsNum = String(42 + index).padStart(4, "0");
  return {
    id: `HFS-T${hfsNum}`,
    legacyId: `TC-${String(index).padStart(3, "0")}`,
    title,
    type,
    priority,
    acFlowRef,
    preconditions,
    steps,
    testData,
    expectedResult,
  };
}

